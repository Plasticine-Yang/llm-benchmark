const d=window.__diorama;
if(!d||!d.ready)throw new Error('Scene did not initialize');
const c=d.renderer.domElement;
// Synthetic DOM event harness: pointer capture requires a physical pointer.
const capture=c.setPointerCapture,release=c.releasePointerCapture;
c.setPointerCapture=()=>{};c.releasePointerCapture=()=>{};
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const before=d.camera.position.clone();
const rect=c.getBoundingClientRect(),x=rect.width*.5,y=rect.height*.6;
c.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:77,pointerType:'mouse',button:0,buttons:1,clientX:x,clientY:y}));
c.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,pointerId:77,pointerType:'mouse',button:0,buttons:1,clientX:x+85,clientY:y-20}));
c.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerId:77,pointerType:'mouse',button:0,buttons:0,clientX:x+85,clientY:y-20}));
await wait(450);
const rotated=d.camera.position.distanceTo(before)>.1;
const distance=d.camera.position.distanceTo(d.controls.target);
c.dispatchEvent(new WheelEvent('wheel',{bubbles:true,cancelable:true,deltaY:-160}));
await wait(400);
const zoomed=d.camera.position.distanceTo(d.controls.target)<distance;
c.dispatchEvent(new MouseEvent('dblclick',{bubbles:true}));
await wait(300);
const start=d.time,frameStart=d.frames;
await wait(700);
const animated=d.time>start&&d.frames>frameStart;
const oldTarget=d.controls.target.clone();
c.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:78,pointerType:'mouse',button:2,buttons:2,clientX:x,clientY:y}));
c.dispatchEvent(new PointerEvent('pointermove',{bubbles:true,pointerId:78,pointerType:'mouse',button:2,buttons:2,clientX:x+35,clientY:y+18}));
c.dispatchEvent(new PointerEvent('pointerup',{bubbles:true,pointerId:78,pointerType:'mouse',button:2,buttons:0,clientX:x+35,clientY:y+18}));
await wait(300);
const panned=d.controls.target.distanceTo(oldTarget)>.01;
c.dispatchEvent(new MouseEvent('dblclick',{bubbles:true}));
let sawOpen=false,sawClosed=false;const deadline=performance.now()+90000;
while(performance.now()<deadline&&!sawClosed){if(d.doorOpen>.7)sawOpen=true;if(sawOpen&&d.doorOpen<.1)sawClosed=true;await wait(400);}
const doorCycle=sawOpen&&sawClosed;
const errors=[];let nonFinite=0;
d.scene.traverse(o=>{if(o.geometry){const a=o.geometry.attributes.position;for(let i=0;i<a.array.length;i++)if(!Number.isFinite(a.array[i]))nonFinite++;}});
if(!rotated)errors.push('drag rotation');if(!zoomed)errors.push('wheel zoom');if(!animated)errors.push('animation clock');if(!panned)errors.push('right drag pan');if(!doorCycle)errors.push('door cycle');if(nonFinite)errors.push('non-finite geometry');
if(errors.length)throw new Error(errors.join(', '));
c.setPointerCapture=capture;c.releasePointerCapture=release;
return {ready:true,rotated,zoomed,panned,doorCycle,animated,nonFinite,rainCount:d.rainCount,drawCalls:d.renderer.info.render.calls,triangles:d.renderer.info.render.triangles,canvasCount:document.querySelectorAll('canvas').length,UIElements:document.querySelectorAll('button,input,nav').length};
