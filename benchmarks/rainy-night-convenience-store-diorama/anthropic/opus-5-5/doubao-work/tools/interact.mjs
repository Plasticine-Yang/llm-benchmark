import puppeteer from 'puppeteer-core';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--use-angle=metal','--ignore-gpu-blocklist'] });
const p = await b.newPage();
await p.setViewport({ width: 1200, height: 800 });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + path.join(root, 'dist/index.html'));
await p.waitForFunction('window.__ready === true');
await new Promise(r => setTimeout(r, 1500));
const a = await p.screenshot({ encoding: 'base64' });
await new Promise(r => setTimeout(r, 800));
const a2 = await p.screenshot({ encoding: 'base64' });
await p.mouse.move(600, 400); await p.mouse.down(); await p.mouse.move(900, 380, { steps: 12 }); await p.mouse.up();
await new Promise(r => setTimeout(r, 800));
await p.screenshot({ path: path.join(root, 'screenshots/after-rotate.png') });
await p.mouse.wheel({ deltaY: -600 });
await new Promise(r => setTimeout(r, 800));
await p.screenshot({ path: path.join(root, 'screenshots/after-zoom.png') });
const uiCount = await p.evaluate(() => document.body.querySelectorAll('*:not(canvas):not(script)').length);
console.log('animated frames differ:', a !== a2, '| non-canvas DOM elements:', uiCount, '| errors:', errs.length ? errs : 'none');
await b.close();
